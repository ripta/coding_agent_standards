#!/usr/bin/env python3
"""Build a wiki's index.md and topic-page report lists from report frontmatter, and lint them.

    bin/wiki build    rewrite index.md and the generated block in topics/*.md
    bin/wiki check    fail if anything is invalid or a generated file is stale
    bin/wiki stale    list topics with reports newer than their `reviewed` date

The rules live in knowledge/wiki.md. `build` and `check` read the index title and intro line
from wiki.json at the repo root. Only git-tracked files, including staged ones, count. A report
another session has written but not yet added never shows up in this session's index.

Git hooks may run this under Python 3.9, so it avoids newer syntax and tomllib.
"""

from __future__ import annotations

import argparse
import html
import json
import os
import re
import subprocess
import sys
from typing import Optional
from urllib.parse import unquote

PROG = "bin/wiki"
CONFIG = "wiki.json"
CONFIG_KEYS = ("title", "intro")
BEGIN = "<!-- BEGIN GENERATED: reports (wiki build) -->"
# Any BEGIN line naming how the block was built, such as an earlier script path. Build rewrites
# it to BEGIN.
ANY_BEGIN = re.compile(r"<!-- BEGIN GENERATED: reports(?: \([^)\n]*\))? -->")
END = "<!-- END GENERATED -->"
INDEX_HEADER = "<!-- Generated by wiki build. Do not edit by hand. -->"
REPORT_NAME = re.compile(r"^(\d{4})(\d{2})(\d{2})-[a-z0-9][a-z0-9.-]*?(\.md|\.html)?$")
LINK = re.compile(r"\]\(([^)\s]+)\)")


class WikiError(Exception):
    """A failure the user must act on; the message says what and where."""


def git_root() -> str:
    out = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True)
    if out.returncode != 0:
        raise WikiError("not inside a git repository")
    return out.stdout.strip()


def tracked() -> list[str]:
    out = subprocess.run(["git", "ls-files", "-z"], capture_output=True, text=True, check=True)
    return [p for p in out.stdout.split("\0") if p and os.path.exists(p)]


def read(path: str) -> str:
    with open(path) as f:
        return f.read()


def load_config() -> dict[str, str]:
    keys = " and ".join(f'"{k}"' for k in CONFIG_KEYS)
    if not os.path.exists(CONFIG):
        raise WikiError(f"{CONFIG} is missing at the repo root; create it with string keys {keys}")

    try:
        config = json.loads(read(CONFIG))
    except ValueError as err:
        raise WikiError(f"{CONFIG} is not valid JSON ({err}); it needs string keys {keys}")

    if not isinstance(config, dict):
        raise WikiError(f"{CONFIG} must be a JSON object with string keys {keys}")

    missing = [k for k in CONFIG_KEYS if not isinstance(config.get(k), str) or not config[k].strip()]
    if missing:
        names = ", ".join(f'"{k}"' for k in missing)
        raise WikiError(f"{CONFIG} lacks {names}; it needs string keys {keys}")

    return {k: config[k].strip() for k in CONFIG_KEYS}


def parse_frontmatter(text: str) -> tuple[Optional[dict], str]:
    """Minimal YAML subset: `key: value`, `key: "quoted"`, `key: [a, b]`."""
    if not text.startswith("---\n"):
        return None, text

    end = text.find("\n---\n", 4)
    if end < 0:
        return None, text

    meta: dict = {}
    for line in text[4:end].splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue

        key, _, val = line.partition(":")
        val = val.strip()
        if val.startswith("[") and val.endswith("]"):
            meta[key.strip()] = [v.strip().strip("'\"") for v in val[1:-1].split(",") if v.strip()]
        else:
            meta[key.strip()] = val.strip("\"'")

    return meta, text[end + 5 :]


def parse_html_meta(text: str) -> dict:
    meta: dict = {}
    for name, content in re.findall(r'<meta\s+name="([^"]+)"\s+content="([^"]*)"', text):
        meta[name] = html.unescape(content)

    if "topics" in meta:
        meta["topics"] = [t.strip() for t in meta["topics"].split(",") if t.strip()]
    if "description" in meta:
        meta["summary"] = meta.pop("description")

    m = re.search(r"<title>(.*?)</title>", text, re.S)
    if m and "title" not in meta:
        meta["title"] = html.unescape(m.group(1).strip())

    return meta


def h1(body: str) -> Optional[str]:
    m = re.search(r"^# (.+)$", body, re.M)
    return m.group(1).strip() if m else None


class Report:
    def __init__(self, name: str, entry: str, date: str) -> None:
        self.name, self.entry, self.date = name, entry, date
        self.meta: dict = {}
        self.title = name

    @property
    def topics(self) -> list[str]:
        return self.meta.get("topics") or []

    @property
    def summary(self) -> str:
        return self.meta.get("summary", "")


def collect(files: list[str], errors: list[str]) -> list[Report]:
    """One Report per top-level entry under reports/YYYY/MM/."""
    groups: dict[str, list[str]] = {}
    for p in files:
        parts = p.split("/")
        if parts[0] != "reports" or len(parts) < 4:
            continue
        groups.setdefault("/".join(parts[:4]), []).append(p)

    reports = []
    for key, members in sorted(groups.items()):
        _, yyyy, mm, name = key.split("/")
        m = REPORT_NAME.match(name)
        if not m:
            errors.append(f"{key}: name must be YYYYMMDD-slug")
            continue

        if (m.group(1), m.group(2)) != (yyyy, mm):
            errors.append(f"{key}: filed under {yyyy}/{mm} but dated {m.group(1)}{m.group(2)}")
        date = f"{m.group(1)}-{m.group(2)}-{m.group(3)}"

        if members == [key]:
            entry = key
        else:
            # Directory report: the one top-level .md carrying frontmatter is the entry.
            top = [p for p in members if p.count("/") == 4 and p.endswith(".md")]
            withfm = [p for p in top if read(p).startswith("---\n")]
            if len(withfm) != 1:
                errors.append(f"{key}/: needs exactly one top-level .md with frontmatter, found {len(withfm)}")
                continue
            entry = withfm[0]

        r = Report(name.rsplit(".", 1)[0] if entry == key else name, entry, date)
        text = read(entry)
        if entry.endswith(".html"):
            r.meta = parse_html_meta(text)
            r.title = r.meta.get("title") or r.name
        else:
            meta, body = parse_frontmatter(text)
            if meta is None:
                errors.append(f"{entry}: missing frontmatter")
                meta = {}
            r.meta = meta
            r.title = meta.get("title") or h1(body) or r.name

        if not r.topics:
            errors.append(f"{entry}: no topics")
        if not r.summary:
            errors.append(f"{entry}: no summary")
        reports.append(r)

    return reports


def load_topics(files: list[str]) -> dict[str, dict]:
    topics = {}
    for p in files:
        if not re.fullmatch(r"topics/[a-z0-9-]+\.md", p):
            continue

        text = read(p)
        meta, body = parse_frontmatter(text)
        meta = meta or {}
        topics[os.path.basename(p)[:-3]] = {
            "path": p,
            "text": text,
            "title": h1(body) or p,
            "area": meta.get("area", "Other"),
            "summary": meta.get("summary", ""),
            "reviewed": meta.get("reviewed", ""),
        }

    return topics


def load_projects(files: list[str]) -> list[tuple[str, str]]:
    names = sorted(set(f.split("/")[1] for f in files if f.startswith("projects/") and f.count("/") >= 2))
    projects = []
    for p in names:
        readme = f"projects/{p}/README.md"
        title = h1(read(readme)) if os.path.exists(readme) else None
        projects.append((p, title or p))
    return projects


def entry_line(r: Report, base: str) -> str:
    rel = os.path.relpath(r.entry, base)
    return f"- **{r.date}** [{r.title}]({rel}): {r.summary}"


def render_index(
    config: dict[str, str], reports: list[Report], topics: dict[str, dict], projects: list[tuple[str, str]]
) -> str:
    out = [INDEX_HEADER, f"# {config['title']}", "", config["intro"], "", "## Topics"]

    counts: dict[str, int] = {}
    for r in reports:
        for t in r.topics:
            counts[t] = counts.get(t, 0) + 1

    areas: dict[str, list[str]] = {}
    for slug, t in topics.items():
        areas.setdefault(t["area"], []).append(slug)

    for area in sorted(areas, key=lambda a: (a == "Other", a)):
        out += ["", f"### {area}", ""]
        for slug in sorted(areas[area]):
            t = topics[slug]
            tail = f": {t['summary']}" if t["summary"] else ""
            out.append(f"- [{t['title']}]({t['path']}) ({counts.get(slug, 0)}){tail}")

    if projects:
        out += ["", "## Projects", ""]
        out += [f"- [{title}](projects/{p}/)" for p, title in projects]

    out += ["", "## Reports", ""]
    month = None
    for r in sorted(reports, key=lambda r: (r.date, r.name), reverse=True):
        if r.date[:7] != month:
            month = r.date[:7]
            out += ["", f"### {month}", ""] if out[-1] != "" else [f"### {month}", ""]
        out.append(entry_line(r, "."))

    return "\n".join(out) + "\n"


def render_topic(t: dict, slug: str, reports: list[Report]) -> str:
    mine = sorted((r for r in reports if slug in r.topics), key=lambda r: (r.date, r.name), reverse=True)
    block = [BEGIN, ""] + [entry_line(r, "topics") for r in mine] + ["", END]
    text = t["text"]

    m = ANY_BEGIN.search(text)
    if m and END in text[m.end() :]:
        post = text[text.index(END, m.end()) + len(END) :]
        return text[: m.start()] + "\n".join(block) + post

    return text.rstrip("\n") + "\n\n## Reports\n\n" + "\n".join(block) + "\n"


def check_links(files: list[str], errors: list[str]) -> None:
    fileset = set(files)
    dirs = {os.path.dirname(f) for f in files}
    while True:
        more = {os.path.dirname(d) for d in dirs if d} - dirs
        if not more:
            break
        dirs |= more

    for p in files:
        if not (p.endswith(".md") and (p.startswith(("reports/", "topics/")) or p == "index.md")):
            continue

        text = re.sub(r"^```.*?^```", "", read(p), flags=re.M | re.S)
        text = re.sub(r"`[^`\n]*`", "", text)
        for target in LINK.findall(text):
            if re.match(r"^[A-Za-z][A-Za-z0-9+.-]*:", target) or target.startswith(("#", "/", "<")):
                continue

            path = target.split("#", 1)[0]
            if not path:
                continue

            resolved = os.path.normpath(os.path.join(os.path.dirname(p), unquote(path)))
            # A link that leaves the repo, such as one into a sibling checkout, cannot be checked.
            if resolved.startswith(".."):
                continue
            if resolved not in fileset and resolved not in dirs:
                errors.append(f"{p}: broken link {target}")


def run(cmd: str) -> int:
    files = tracked()
    errors: list[str] = []
    reports = collect(files, errors)
    topics = load_topics(files)

    for p in files:
        if "/" not in p and REPORT_NAME.match(p):
            errors.append(f"{p}: dated report at repo root; move it to reports/{p[:4]}/{p[4:6]}/")

    for r in reports:
        for t in r.topics:
            if t not in topics:
                errors.append(f"{r.entry}: topic '{t}' has no topics/{t}.md")

    used = {t for r in reports for t in r.topics}
    warnings = [f"topics/{s}.md: no reports tagged '{s}'" for s in topics if s not in used]

    if cmd == "stale":
        for slug, t in sorted(topics.items()):
            newer = sorted(r.entry for r in reports if slug in r.topics and r.date > t["reviewed"])
            if newer:
                print(f"{t['path']} (reviewed {t['reviewed'] or 'never'}): {len(newer)} newer")
                for e in newer:
                    print(f"  {e}")
        return 0

    config = load_config()
    wanted = {"index.md": render_index(config, reports, topics, load_projects(files))}
    for slug, t in topics.items():
        wanted[t["path"]] = render_topic(t, slug, reports)

    if cmd == "build":
        for path, text in wanted.items():
            old = read(path) if os.path.exists(path) else None
            if old != text:
                with open(path, "w") as f:
                    f.write(text)
                print(f"wrote {path}")
    else:
        check_links(files, errors)
        for path, text in wanted.items():
            old = read(path) if os.path.exists(path) else None
            if old != text:
                errors.append(f"{path}: stale; run {PROG} build")

    for w in warnings:
        print(f"warning: {w}", file=sys.stderr)
    for e in errors:
        print(f"error: {e}", file=sys.stderr)
    return 1 if errors else 0


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        prog=PROG, description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    sub = parser.add_subparsers(dest="command")
    sub.add_parser("build", help="rewrite index.md and the generated block in topics/*.md")
    sub.add_parser("check", help="fail if anything is invalid or a generated file is stale")
    sub.add_parser("stale", help="list topics with reports newer than their `reviewed` date")
    args = parser.parse_args(argv)

    try:
        os.chdir(git_root())
        return run(args.command or "check")
    except WikiError as err:
        print(f"error: {err}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
