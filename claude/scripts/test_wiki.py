"""Tests for wiki.py. Run: uv run --with pytest pytest claude/scripts"""

import json
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

WIKI = Path(__file__).parent / "wiki.py"
REPORT = "reports/2026/03/20260312-cache-eviction-study.md"
CONFIG = {"title": "Example wiki", "intro": "Start here."}


def _report(
    topics: str = "[caching, storage-engine]",
    summary: str = "LRU beats FIFO for this workload.",
    extra: str = "",
    title: str = "Cache eviction study",
) -> str:
    return f'---\ntopics: {topics}\nsummary: "{summary}"\n{extra}---\n\n# {title}\n\nFindings.\n'


def _topic(title: str, area: str = "Infrastructure", reviewed: str = "2026-03-01") -> str:
    return (
        f'---\narea: {area}\nsummary: "One line."\nreviewed: {reviewed}\n---\n\n# {title}\n\n'
        "## Current position\n\n## Open questions\n\n## Related\n"
    )


def _git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True, check=True).stdout


def _write(repo: Path, rel: str, text: str, add: bool = True) -> Path:
    path = repo / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    if add:
        _git(repo, "add", "--", rel)
    return path


def _wiki(repo: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, str(WIKI), *args], cwd=repo, capture_output=True, text=True)


@pytest.fixture
def repo(tmp_path: Path) -> Path:
    """A wiki with one report and its two topic pages, all staged but never committed."""
    _git(tmp_path, "init", "-q")
    _write(tmp_path, "wiki.json", json.dumps(CONFIG))
    _write(tmp_path, REPORT, _report())
    _write(tmp_path, "topics/caching.md", _topic("Caching"))
    _write(tmp_path, "topics/storage-engine.md", _topic("Storage engine"))
    return tmp_path


def _build(repo: Path) -> subprocess.CompletedProcess:
    result = _wiki(repo, "build")
    _git(repo, "add", "--", *(p for p in ("index.md", "reports/index.md", "topics") if (repo / p).exists()))
    return result


def _report_list(repo: Path) -> str:
    return (repo / "reports/index.md").read_text()


def _in_reports(rel: str) -> str:
    """A report path as reports/index.md links it."""
    return rel.removeprefix("reports/")


def test_build_writes_index_and_topic_blocks(repo: Path) -> None:
    result = _build(repo)
    assert result.returncode == 0, result.stderr

    index = (repo / "index.md").read_text()
    assert index.startswith("<!-- Generated by wiki build. Do not edit by hand. -->\n# Example wiki\n\nStart here.\n")
    assert "### Infrastructure" in index
    assert "- [Caching](topics/caching.md) (1): One line." in index
    assert "## Reports\n\n- [All reports, newest first](reports/index.md) (1)\n" in index
    assert "Cache eviction study" not in index

    reports = _report_list(repo)
    assert reports.startswith("<!-- Generated by wiki build. Do not edit by hand. -->\n# Reports\n")
    assert "](../index.md)" in reports
    assert "\n## 2026-03\n" in reports
    entry = f"- **2026-03-12** [Cache eviction study]({_in_reports(REPORT)}): LRU beats FIFO for this workload."
    assert entry in reports

    topic = (repo / "topics/caching.md").read_text()
    assert "<!-- BEGIN GENERATED: reports (wiki build) -->" in topic
    assert f"](../{REPORT})" in topic
    assert topic.rstrip().endswith("<!-- END GENERATED -->")


def test_check_passes_after_build_and_fails_when_stale(repo: Path) -> None:
    _build(repo)
    result = _wiki(repo, "check")
    assert result.returncode == 0, result.stderr

    _write(repo, "reports/2026/03/20260320-write-amplification.md", _report("[storage-engine]"))
    result = _wiki(repo, "check")
    assert result.returncode == 1
    assert "error: index.md: stale; run bin/wiki build" in result.stderr
    assert "error: reports/index.md: stale; run bin/wiki build" in result.stderr
    assert "error: topics/storage-engine.md: stale; run bin/wiki build" in result.stderr
    assert "topics/caching.md: stale" not in result.stderr


def test_first_build_of_a_wiki_with_no_reports(repo: Path) -> None:
    """A new wiki has no reports/ directory yet, so build must create it for the report list."""
    _git(repo, "rm", "-q", "--cached", "--", REPORT)
    shutil.rmtree(repo / "reports")
    result = _build(repo)
    assert result.returncode == 0, result.stderr
    assert "- [All reports, newest first](reports/index.md) (0)" in (repo / "index.md").read_text()
    assert _wiki(repo, "check").returncode == 0


@pytest.mark.parametrize("config", [None, "{}", '{"title": "Example wiki"}', "not json"])
@pytest.mark.parametrize("cmd", ["build", "check"])
def test_build_and_check_require_wiki_json(repo: Path, cmd: str, config: str) -> None:
    if config is None:
        _git(repo, "rm", "-q", "--cached", "wiki.json")
        (repo / "wiki.json").unlink()
    else:
        (repo / "wiki.json").write_text(config)

    result = _wiki(repo, cmd)
    assert result.returncode == 1
    assert "wiki.json" in result.stderr
    assert '"title" and "intro"' in result.stderr
    assert not (repo / "index.md").exists()


def test_old_marker_is_rewritten_by_build_and_flagged_by_check(repo: Path) -> None:
    old = (
        _topic("Caching")
        + "\n## Reports\n\n<!-- BEGIN GENERATED: reports (scripts/build-index.py) -->\n"
        + "\n<!-- END GENERATED -->\n\nTrailing note.\n"
    )
    _build(repo)
    _write(repo, "topics/caching.md", old)

    result = _wiki(repo, "check")
    assert result.returncode == 1
    assert "error: topics/caching.md: stale; run bin/wiki build" in result.stderr

    _build(repo)
    topic = (repo / "topics/caching.md").read_text()
    assert "build-index" not in topic
    assert topic.count("<!-- BEGIN GENERATED: reports (wiki build) -->") == 1
    assert topic.count("## Reports") == 1
    assert f"](../{REPORT})" in topic
    assert topic.endswith("<!-- END GENERATED -->\n\nTrailing note.\n")
    assert _wiki(repo, "check").returncode == 0


