def test_broken_link(repo: Path) -> None:
    body = _report() + "\nSee [the trace](trace.md), [a dir](../03/), and [outside](../../../../x.md).\n"
    body += "\n```\n[skipped](nowhere.md)\n```\n"
    _write(repo, REPORT, body)
    _build(repo)
    result = _wiki(repo, "check")
    assert result.returncode == 1
    assert f"error: {REPORT}: broken link trace.md" in result.stderr
    assert "../03/" not in result.stderr
    assert "outside" not in result.stderr
    assert "nowhere.md" not in result.stderr


def test_directory_report_needs_exactly_one_frontmatter_md(repo: Path) -> None:
    base = "reports/2026/03/20260316-tier-sizing"
    _write(repo, f"{base}/README.md", _report())
    _write(repo, f"{base}/data.md", _report())
    result = _wiki(repo, "check")
    assert f"error: {base}/: needs exactly one top-level .md with frontmatter, found 2" in result.stderr

    _write(repo, f"{base}/data.md", "# Raw data\n")
    _write(repo, f"{base}/figures/hit-ratio.md", _report())
    _build(repo)
    assert f"[Cache eviction study]({base}/README.md)" in (repo / "index.md").read_text()
    assert _wiki(repo, "check").returncode == 0


def test_html_report_reads_meta(repo: Path) -> None:
    page = (
        '<html><head><title>Eviction &amp; admission</title>\n'
        '<meta name="topics" content="caching, storage-engine">\n'
        '<meta name="description" content="Admission filters halve churn.">\n</head></html>\n'
    )
    rel = "reports/2026/03/20260317-admission.html"
    _write(repo, rel, page)
    _build(repo)
    assert f"- **2026-03-17** [Eviction & admission]({rel}): Admission filters halve churn." in (
        repo / "index.md"
    ).read_text()
    assert _wiki(repo, "check").returncode == 0


def test_stale_lists_topics_with_newer_reports(repo: Path) -> None:
    _write(repo, "topics/caching.md", _topic("Caching", reviewed="2026-03-20"))
    _write(repo, "reports/2026/02/20260210-early.md", _report("[storage-engine]"))
    result = _wiki(repo, "stale")
    assert result.returncode == 0
    assert result.stdout == f"topics/storage-engine.md (reviewed 2026-03-01): 1 newer\n  {REPORT}\n"


def test_stale_runs_without_wiki_json(repo: Path) -> None:
    (repo / "wiki.json").unlink()
    assert _wiki(repo, "stale").returncode == 0


